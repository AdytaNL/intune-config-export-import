<#
.SYNOPSIS
    Generates a mapping file from an export folder.

.DESCRIPTION
    Reads all .meta.json files in the export folder and collects:
      - all unique group names (for groupMappings)
      - all placeholder tokens found (for tokenOverrides)

    Fill in the resulting mapping file with the values for the target tenant
    before you run Import-IntuneDeviceConfigurations.ps1.

.PARAMETER SourcePath
    Folder with the exported JSON files.

.PARAMETER OutputFile
    Path of the mapping file to generate.
    Default: <SourcePath>\mapping-template.json

.EXAMPLE
    .\New-IntuneImportMapping.ps1 -SourcePath "C:\Export\Contoso" -OutputFile "C:\Export\Contoso\mapping-fabrikam.json"
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true)]  [string]$SourcePath,
    [Parameter(Mandatory = $false)] [string]$OutputFile = (Join-Path $SourcePath "mapping-template.json")
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $SourcePath)) { throw "SourcePath not found: $SourcePath" }

$metaFiles = Get-ChildItem -Path $SourcePath -Filter "*.meta.json"
if ($metaFiles.Count -eq 0) { throw "No .meta.json files found in $SourcePath" }

Write-Host "`nProcessing $($metaFiles.Count) meta files..." -ForegroundColor Cyan

$allGroupNames  = [System.Collections.Generic.SortedSet[string]]::new()
$allTokens      = [System.Collections.Generic.SortedSet[string]]::new()
$sourceTenantId = $null

foreach ($f in $metaFiles) {
    $meta = Get-Content $f.FullName -Raw -Encoding UTF8 | ConvertFrom-Json

    if (-not $sourceTenantId -and $meta.sourceTenantId) {
        $sourceTenantId = $meta.sourceTenantId
    }

    # Collect group names
    foreach ($asgn in $meta.assignments) {
        if ($asgn.groupName) { $null = $allGroupNames.Add($asgn.groupName) }
    }

    # Collect tokens
    if ($meta.placeholders) {
        foreach ($prop in $meta.placeholders.PSObject.Properties) {
            $null = $allTokens.Add($prop.Name)
        }
    }
}

# groupMappings: same name by default (1:1 for groups with the same name)
$groupMappings = [ordered]@{}
foreach ($name in $allGroupNames) {
    $groupMappings[$name] = $name   # <- replace with the target group name if it differs
}

# tokenOverrides for any token other than SOURCE_TENANT_ID and the group tokens
$tokenOverrides = [ordered]@{}
foreach ($token in $allTokens) {
    if ($token -ne 'SOURCE_TENANT_ID' -and $token -notmatch '^(GROUP_|EXCL_GROUP_)') {
        $tokenOverrides[$token] = ""   # <- fill in by hand
    }
}

$mapping = [ordered]@{
    '_comment'       = "Generated by New-IntuneImportMapping.ps1 - fill in the values for the target tenant"
    '_sourceTenant'  = $sourceTenantId
    'SOURCE_TENANT_ID' = ""    # <- tenant ID of the TARGET tenant
    'groupMappings'  = $groupMappings
}

if ($tokenOverrides.Count -gt 0) {
    $mapping['tokenOverrides'] = $tokenOverrides
}

$json = $mapping | ConvertTo-Json -Depth 5
# Full path: [System.IO.File] resolves relative paths against the process directory, not $PWD
$OutputFile = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputFile)
[System.IO.File]::WriteAllText($OutputFile, $json, [System.Text.Encoding]::UTF8)

Write-Host "`nMapping template created: $OutputFile" -ForegroundColor Green
Write-Host "  Unique groups : $($allGroupNames.Count)" -ForegroundColor Cyan
Write-Host "  Extra tokens  : $($tokenOverrides.Count)" -ForegroundColor Cyan
Write-Host "`nFill in:" -ForegroundColor Yellow
Write-Host "  SOURCE_TENANT_ID  -> tenant ID of the target tenant" -ForegroundColor Yellow
foreach ($name in $allGroupNames) {
    Write-Host "  Group: $name" -ForegroundColor Yellow
}
if ($tokenOverrides.Count -gt 0) {
    Write-Host "`n  Extra tokens (fill in under tokenOverrides):" -ForegroundColor Yellow
    foreach ($token in $tokenOverrides.Keys) {
        Write-Host "    $token" -ForegroundColor Yellow
    }
}
